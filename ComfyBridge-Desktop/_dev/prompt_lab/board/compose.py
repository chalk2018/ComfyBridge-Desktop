from __future__ import annotations

import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
LAYOUTS = {
    "G4": {"n": 4, "rows": 2, "cols": 2, "ratio": "16:9", "size": (1536, 864)},
    "G6": {"n": 6, "rows": 2, "cols": 3, "ratio": "8:3", "size": (2304, 864)},
    "G9": {"n": 9, "rows": 3, "cols": 3, "ratio": "16:9", "size": (1536, 864)},
}
CN = "一二三四五六七八九"
LINE_STYLES = {
    "W1": "纯黑白线稿，只有黑色的线条和纯白的底色，像用黑色针管笔在白纸上画的分镜。没有任何颜色、没有任何灰色调、没有阴影面和渐变、没有网点纸纹理、没有铅笔涂抹痕迹。线条干净利落，外轮廓线略粗，内部结构线略细，转折处有明显的粗细变化，用少量平行排线交代结构，不糊成一团黑。画面里的所有部位都用线条表现，不上色，不给任何局部填色。",
    "W2": "工业设计草图风格的线稿，以细而均匀的线条为主，用少量结构辅助线交代转折与接缝，线条精准克制，像设计师手绘的分镜手稿，只有黑线和白纸，所有部位都不上色。",
    "W3": "美式动画分镜线稿，只用黑色勾线笔勾出干净轮廓，暗部用稀疏的交叉排线表示，不填任何黑色块面，不画灰调，画面只有细黑线和白纸，所有部位都不上色。",
    "W4": "铅笔线稿，用 2B 铅笔勾线，线条有轻微抖动和轻重变化，只在结构转折处轻扫几笔，不涂阴影不做渐变，白纸底色。",
}
COLOR_TAIL = "彩色成片，色彩自然统一，光线柔和，材质细节清晰，电影质感。"
TAIL = "整张故事板画风统一，各格的光线、色调与材质保持一致；画面里不出现任何文字、数字、编号、字幕、水印、Logo、箭头、气泡、外框或额外的第十格。"


def cell_pos(layout: str, i: int) -> str:
    L = LAYOUTS[layout]
    r, c = divmod(i, L["cols"])
    names = {0: "左上", 1: "右上", 2: "左下", 3: "右下"}
    if layout == "G4":
        return names[i]
    if layout == "G6":
        return f"第 {r+1} 行第 {c+1} 列"
    return f"第 {r+1} 行第 {c+1} 列"


def compose(layout: str, cells: list[str], ink: str = "color", line_style: str = "W3",
            refs: int = 0) -> str:
    L = LAYOUTS[layout]
    blocks: list[str] = []
    if ink == "line":
        blocks.append("这是一张纯黑白线稿电影分镜故事板。严格黑白，绝对不允许任何颜色、彩色色块或彩色光影。"
                      "Strictly black and white line art only, absolutely no color anywhere in the image.")
    blocks.append(
        f"生成一张横向电影分镜故事板，{L['ratio']} 横向长方形画面，是一张完整连续的图，不是多张图的拼贴。"
        f"整体平均分成 {L['rows']} 行 {L['cols']} 列，共 {L['n']} 个等大的长方形格子（{L['cols']}×{L['rows']} 分镜格），"
        f"所有格子紧密拼合在一起、正好填满整张画布；每一格都是一幅独立的 16:9 横屏电影画面。"
        f"格子之间只留均匀的纯白色空隙，没有黑色分割线、没有外边框、没有网格线、没有编号、没有文字。"
        f"极其重要：这不是漫画分格，绝对不要给任何一格画黑色矩形边框或细线框，画面最外圈也不要画外框；"
        f"每一格的内容直接顶到该格边缘，格子之间只靠纯白留白区分。"
        f"严格按照从左到右、从上到下的顺序阅读各格，不得重排、合并、跳过、复制或新增任何格子。"
    )
    lines = []
    for i, text in enumerate(cells):
        t = (text or "").strip()
        head = f"第 {CN[i]} 格（{cell_pos(layout, i)}）："
        if not t:
            lines.append(head + "这一格刻意完全留空：整格是纯白色，不画任何人物、场景、物体、纹理或色块，绝对不要画这个格子的矩形边框或任何线条，让它的白色和格子之间的白色空隙融为一体，看不出任何边界；不写任何文字或编号。")
        else:
            lines.append(head + t)
    blocks.append("【逐格画面】\n" + "\n".join(lines))

    if refs == 0:
        blocks.append(
            "【主体一致性】所有画有内容的格子里，主角必须是同一个人或同一个主体：五官、发型、体型、服装款式与配色、标志物在每一格都完全一致；"
            "只改变姿态、动作、表情、景别和镜头角度，不更换角色、不换装、不出现第二个主角。"
            "若某一格没有写明主体外观，直接沿用第 1 格已经出现的主体；严禁出现只有背景、没有主体的格子。"
        )
    else:
        mentions: list[str] = []
        for i, t in enumerate(cells):
            for m in re.findall(r"图\s*([1-9])", t or ""):
                mentions.append(f"第 {CN[i]} 格以图 {m} 中的角色或主体为身份基准，严格保持其五官、发型、体型、服装与配色一致；只按该格文字改变姿态、动作、表情、景别与所处场景。")
        if mentions:
            blocks.append("【参考图使用】" + "\n".join(dict.fromkeys(mentions)))
        else:
            blocks.append("【参考图使用】没有任何一格引用参考图里的人物身份。参考图只提供环境、材质与画风线索；"
                          "各格人物长相、发型、服装完全按该格文字重新创作，不照搬参考图人物的五官与衣着，"
                          "不因为上传了参考图就让不同格子变成同一个人。")
        blocks.append(
            "【参考图通用规则】参考图只是角色身份、场景、道具与画风的素材线索，不是可以直接贴进格子的图片；"
            "每一格都必须重新绘制成真实的电影画面，严禁把任何参考图整张复制、缩放或裁剪后贴到格子里。"
            "若某张参考图是平面图、鸟瞰图、布局草图或带标注的示意图，只取其中各元素的相对方位与布局关系，"
            "绝对不要照搬其色块、线条、文字、数字、箭头、外框和边框，成图里不得出现平面示意图效果。"
            "任何格子都不要把参考图本身画成挂在墙上的画、海报、屏幕、展板或白板，也不要在画面里出现一整块白色示意图面板；"
            "参考图里的方位与内容必须变成真实场景本身。"
        )

    blocks.append("【画法】" + (LINE_STYLES.get(line_style, LINE_STYLES["W3"]) +
                             "整张故事板所有格子统一使用这一种线稿画法。无论参考图是彩色照片还是彩色画面，"
                             "成图都必须是纯黑白线稿：所有格子、人物、衣服、围巾、天空、夕阳、道具和背景一律不上色，"
                             "不出现任何颜色或彩色色块，只允许黑色线条和纯白纸底。" if ink == "line" else COLOR_TAIL))
    blocks.append(TAIL + " 任何格子都不画矩形边框，空白格纯白无框。" +
                  (" 全图逐格检查：只有黑色线条与纯白纸底，不允许出现任何颜色、彩色天空或彩色光影。" if ink == "line" else ""))
    return "\n\n".join(blocks)


