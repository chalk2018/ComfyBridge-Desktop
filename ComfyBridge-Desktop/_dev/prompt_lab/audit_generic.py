def main() -> None:
    bad = 0
    for label, text in CASES:
        plan = _view_plan(text)
        name = _prop_name(text)
        prompt = compose_prop("t2i", "MV", text, ref="none", ink="color",
                              style="写实摄影")
        keep_prop = f"道具：{text}" in prompt
        flag = []
        if plan["n"] == 1:
            flag.append("判为对称→只画1个")
        if not name or name not in text:
            flag.append(f"名字={name!r}")
        if not keep_prop:
            flag.append("原名未原样保留")
        if flag:
            bad += 1
        print(f"{label:<8} n={plan['n']} {plan['source']:<9} name={name!r:<12}"
              f"{'  <<< ' + ' / '.join(flag) if flag else ''}")
    print(f"\n{len(CASES)} 条，可疑 {bad} 条")


if __name__ == "__main__":
    main()
