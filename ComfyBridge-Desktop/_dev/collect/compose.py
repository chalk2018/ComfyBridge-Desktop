def _person(spec: dict) -> bool:
    blob = spec.get("主体", "") + spec.get("补充", "")
    return any(w in blob for w in ("人", "女", "男", "孩", "少年", "老人", "模特", "舞者", "厨师", "陶艺"))


def _len(text: str) -> int:
    return len(text.replace("\n", "").replace(" ", ""))


def _token_refs(refs: list[dict]) -> tuple[list[str], list[str]]:
    counter = {"image": 0, "video": 0, "audio": 0}
    lines, tokens = [], []
    for r in refs:
        counter[r["kind"]] += 1
        tok = f"[{KIND_CN[r['kind']]} {counter[r['kind']]}]"
        tokens.append(tok)
        lines.append(f"{tok} {r['desc']}；它在这里的角色是{REFS_ROLE.get(r['role'], '提供画面参考')}。")
    return tokens, lines


def _finish(parts: list[str], detail: list[str], need: int, key: str, tail: list[str],
            has_person: bool = False) -> str:
    """先补足字数（放在正向描述末尾、负向之前），再接输出参数与负向。

    * 最多补 4 句，避免堆成清单；
    * 「（有人物时）」这类限定句只在主体确实有人时才用。
    """
    body = parts[:]
    used: set[str] = set()
    i = 0
    added = 0
    while _len("\n".join(body + tail)) < need and i < len(detail) + 6 and added < 4:
        cand = detail[(int(hashlib.md5((key + str(i)).encode()).hexdigest()[:6], 16) + i) % len(detail)]
        if cand in used or (not has_person and ("有人物时" in cand or cand.startswith("人物状态"))):
            i += 1
            continue
        used.add(cand)
        if not used.__len__() > 1 and not any(x.startswith("【延伸细节】") for x in body):
            body.append("【延伸细节】")
        body.append(cand)
        added += 1
        i += 1
    return "\n".join(body + tail)


def _canvas(size: list[int] | None, long_edge: int) -> tuple[int, int, str]:
    """按参考素材的实际比例算输出画幅（长边取整到 16 的倍数），并给出横/竖说明。"""
    w, h = (size or [1536, 864])[:2]
    if w <= 0 or h <= 0:
        w, h = 1536, 864
    k = long_edge / max(w, h)
    ow = max(16, int(round(w * k / 16)) * 16)
    oh = max(16, int(round(h * k / 16)) * 16)
    if h > w * 1.02:
        how = "竖版，与参考素材同比例"
    elif w > h * 1.02:
        how = "横版，与参考素材同比例"
    else:
        how = "方幅，与参考素材同比例"
    return ow, oh, how


def _env(scene: str, lead: str) -> str:
    """把「环境」写顺：抽象题材没有具体场景时，不要出现「所处环境是无环境」。"""
    scene = (scene or "").strip()
    if not scene or scene in ("无", "纯背景"):
        return "画面不依赖具体场景，环境就是画面本身。"
    if "无环境" in scene:
        if "纯色背景" in scene:
            return f"{lead}纯色背景，不添加其他场景元素。"
        return "画面不依赖具体场景，环境就是画面本身。"
    return f"{lead}{scene}。"


