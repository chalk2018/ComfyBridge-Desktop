"""把需求 A 里那三条示例的提示词改成与素材严格对应的引用写法（[图片 N] / [视频 N] / [音频 N]）。

示例本身是功能演示，保持短小，但引用编号必须和卡片上的缩略图一一对应。
"""
from __future__ import annotations

import httpx

API = "http://127.0.0.1:8190/api/prompt-templates"

NEW = {
    "参考生图 · 山湖晨光构图复位": (
        "【参考生图】以 [图片 1] 为构图锚点重建画面：山脊线的走向、湖面反光带的位置、远山的层次关系"
        "全部保留，主体在画面中的占比不变，只替换环境细节与时间感。人物姿态与服装取自 [图片 2]，"
        "保留侧身站姿与微低头的角度，肤色随环境光偏暖，避开塑料感高光。运镜与节奏参考 [视频 1]："
        "起幅中景缓推，两秒后切近景，收在侧逆光特写。输出 3:4 竖构图，浅景深，背景轻微失焦；"
        "负向约束：不要改动山脊轮廓，不要加入文字与边框。"
    ),
    "参考生视频 · 运镜节奏复刻": (
        "【参考生视频】沿用 [视频 1] 的运镜节奏与景别变化：起幅中景缓推，两秒后切近景，收在侧逆光"
        "特写上，镜头速度与前段一致，不做突然变速。光比与逆光轮廓参考 [视频 2]，保持右侧主光、"
        "暗部留细节的高反差质感。画面内容以 [图片 1] 为首帧：山脊与湖面构图不变，只让水面细浪与"
        "云层缓慢移动。8 秒，24fps，稳定器质感；负向约束：不要换景别、不要出现人物、不要画面抖动。"
    ),
    "参考生音乐 · 古筝动机延展": (
        "【参考生音乐】以 [音频 1] 的音色与调式为准，把四小节古筝动机延展成 30 秒铺底：保留拨弦的"
        "颗粒感与轻微走音，音区集中在中高音，不做电声处理。低频参考 [音频 2] 的环境底噪，作为持续"
        "铺底的一层，音量压在 -28dB 以下，给主奏留出空间。结构按「动机呈现—加花变奏—回声收尾」"
        "推进，末尾 4 秒自然衰减到静音；负向约束：不要加入鼓组，不要压缩到失真，不要有突兀剪辑点。"
    ),
}


def main() -> None:
    d = httpx.get(API, timeout=120).json()["data"]
    hit = 0
    for t in d["templates"]:
        content = NEW.get(t["title"])
        if content is None:
            continue
        body = {
            "title": t["title"],
            "content": content,
            "category": t["category"],
            "tags": t.get("tags", []),   # 接口收标签 id
            "media": t["media"],
        }
        r = httpx.put(f"{API}/item/{t['id']}", json=body, timeout=120)
        print(t["title"], r.status_code, r.json().get("ok"), "字数",
              len("".join(content.split())))
        hit += 1
    print("更新", hit, "条")


if __name__ == "__main__":
    main()
