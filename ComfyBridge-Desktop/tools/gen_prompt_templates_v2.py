def pad_content(content, floor, idx, pool):
    """循环叠加补充段落，直到汉字数达标。每次取不同段落避免重复。"""
    guard = 0
    while cn_len(content) < floor and guard < 20:
        seg = pool[(idx + guard) % len(pool)]
        content += "\n\n" + seg
        guard += 1
    return content


