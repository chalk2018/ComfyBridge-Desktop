def save_tags():
    lines = ["# 标签库", "", "> ComfyBridge 提示词模板库的标签。一个标签一个色，颜色不重复。", ""]
    for tid, name, color in TAGS:
        lines += [f'<!-- CBTAG id="{tid}" color="{color}" -->', name, "<!-- CBTAG-END -->", ""]
    (BASE / "标签.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def save_cat(fname, cn, items):
    lines = [f"# {cn} · 精品提示词模板", "",
             "> ComfyBridge 提示词模板库自动维护。每条为结构化长提示词，请尽量在页面里编辑，手改后刷新页面即可生效。", ""]
    for t in items:
        lines.append(render_tpl(t))
    (BASE / fname).write_text("\n".join(lines) + "\n", encoding="utf-8")


def stat(items, name, floor):
    lens = [cn_len(t["content"]) for t in items]
    bad = sum(1 for x in lens if x < floor)
    print(f"  {name}: {len(items)} 条 | 汉字数 min={min(lens)} max={max(lens)} avg={sum(lens)//len(lens)} | 不达标(<{floor})={bad}")


def main():
    BASE.mkdir(parents=True, exist_ok=True)
    save_tags()
    vids, imgs, auds = gen_video(), gen_image(), gen_audio()
    print("字数统计：")
    stat(vids, "视频", 1000)
    stat(imgs, "图片", 600)
    stat(auds, "音频", 1000)
    save_cat("视频.md", "视频", vids)
    save_cat("图片.md", "图片", imgs)
    save_cat("音频.md", "音频", auds)
    total = len(vids) + len(imgs) + len(auds)
    print(f"生成完成：视频 {len(vids)} + 图片 {len(imgs)} + 音频 {len(auds)} = {total}，标签 {len(TAGS)}")


if __name__ == "__main__":
    main()
